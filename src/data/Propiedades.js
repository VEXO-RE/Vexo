window.getImgPrincipal = function(d) {
  if (!d) return "";
  if (d.foto_principal_url && d.foto_principal_url.trim()) return d.foto_principal_url;
  if (Array.isArray(d.imagenes) && d.imagenes.length > 0 && d.imagenes[0]) return d.imagenes[0];
  if (d.imagen_fallback) return d.imagen_fallback;
  return "";
};

window.getDesarrolloBySlug = function(slug) {
  return (window.DESARROLLOS||[]).find(function(d){ return d.slug===slug || d.url_slug===slug; });
};

window.getDesarrolloById = function(id) {
  return (window.DESARROLLOS||[]).find(function(d){ return String(d.id)===String(id); });
};

